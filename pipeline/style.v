module pipeline

// Стиль проявки (профиль, как профили Adobe «Портрет», «Пейзаж», «Яркий»):
// базовый слой под ползунками - свой контраст, насыщенность, сочность и
// поправки 8 диапазонов оттенков (как HSL). Ползунки пользователя стоят
// на нуле и складываются со стилем: контраст и сочность - сумма,
// насыщенность - произведение, HSL - сумма по диапазонам. Производное
// поле Params.style (по ключу профиля кадра, style_by_key); в Ч/Б
// действует только контраст. Свои значения, подобранные на глаз, - не
// таблицы Adobe и не RawTherapee.

// Style - добавки стиля (нули и sat = 1 - стиля нет)
pub struct Style {
pub mut:
	contrast f32 // к контрасту (единицы ползунка, -4..4)
	sat      f32 = 1 // множитель насыщенности
	vib      f32 // к сочности (-100..100)
	hue      [8]f32 // к HSL: оттенок, насыщенность, яркость диапазонов
	hsat     [8]f32
	lum      [8]f32
}

// Ключи стилей (EditState.profile) и названия. Порядок диапазонов -
// hsl_centers: красный, оранжевый, жёлтый, зелёный, голубой, синий,
// фиолетовый, пурпурный
pub const style_keys = ['portrait', 'landscape', 'vivid']
pub const style_names = ['Портрет', 'Пейзаж', 'Яркий']

// style_by_key - стиль по ключу; неизвестный или '' - без стиля
pub fn style_by_key(key string) Style {
	return match key {
		// Мягче контраст, кожа (оранжевый, красный) спокойнее и чуть
		// светлее, остальное - почти как есть
		'portrait' {
			Style{
				contrast: -0.08
				vib:      5
				hue:      [f32(0), -3, 0, 0, 0, 0, 0, 0]!
				hsat:     [f32(-8), -12, -5, 0, 0, 0, 0, 0]!
				lum:      [f32(4), 8, 4, 0, 0, 0, 0, 0]!
			}
		}
		// Контраст, сочная зелень и небо: голубое и синее насыщеннее и
		// чуть глубже, зелень чуть к жёлтому
		'landscape' {
			Style{
				contrast: 0.2
				vib:      12
				hue:      [f32(0), 0, 0, -4, 0, 0, 0, 0]!
				hsat:     [f32(0), 0, 8, 15, 12, 8, 0, 0]!
				lum:      [f32(0), 0, 3, 0, -5, -6, 0, 0]!
			}
		}
		// Яркий: контраст и насыщенность всего кадра
		'vivid' {
			Style{
				contrast: 0.25
				sat:      1.12
				vib:      15
			}
		}
		else {
			Style{}
		}
	}
}

// Действующие значения (ползунок + стиль)

fn eff_contrast(p &Params) f32 {
	return p.contrast + p.style.contrast
}

fn eff_vibrance(p &Params) f32 {
	v := p.vibrance + p.style.vib
	return if v > 100 { 100 } else if v < -100 { -100 } else { v }
}

fn eff_hsl(p &Params) ([8]f32, [8]f32, [8]f32) {
	mut h := p.hsl_hue
	mut s := p.hsl_sat
	mut l := p.hsl_lum
	for i in 0 .. 8 {
		h[i] += p.style.hue[i]
		s[i] += p.style.hsat[i]
		l[i] += p.style.lum[i]
	}
	return h, s, l
}
